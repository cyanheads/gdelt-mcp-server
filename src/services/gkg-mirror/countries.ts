/** Lowercase letters only: `unitedarabemirates`, `United Arab Emirates`, and `guinea-bissau` resolve alike. */
function nameKey(value: string): string {
  return value.toLowerCase().replace(/[^a-z]/g, '');
}

const nameByFips = new Map<string, string>(DOC_COUNTRIES.map((c) => [c.fips, c.name]));

const fipsByName = new Map<string, string>();
for (const c of DOC_COUNTRIES) {
  for (const name of [c.name, ...(c.aliases ?? [])]) {
    const key = nameKey(name);
    if (!fipsByName.has(key)) fipsByName.set(key, c.fips);
  }
}

/** Letters plus the punctuation a written-out name can carry (`bahamas,the`, `guinea-bissau`, `coted'ivoire`). */
const COUNTRY_VALUE = /^[A-Za-z,.'-]+$/;

/**
 * Resolve a `sourcecountry:` value to its FIPS code: a two-letter FIPS code, or a country name
 * written without spaces, in any case. Undefined when neither table lists it.
 */
export function resolveDocCountry(value: string): string | undefined {
  if (!COUNTRY_VALUE.test(value)) return;
  if (value.length === 2) {
    const fips = value.toUpperCase();
    return nameByFips.has(fips) ? fips : undefined;
  }
  return fipsByName.get(nameKey(value));
}

/** The display name of a FIPS code, or undefined for a code neither table names. */
export function docCountryName(fips: string): string | undefined {
  return nameByFips.get(fips);
}
